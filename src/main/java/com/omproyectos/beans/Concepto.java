
package com.omproyectos.beans;

public class Concepto {
    private int codConcepto;
    private String descripcion;
    private String tipo;
    private double totalConcepto;

    public Concepto() {
    }

    public int getCodConcepto() {
        return codConcepto;
    }

    public void setCodConcepto(int codConcepto) {
        this.codConcepto = codConcepto;
    }

    public String getDescripcion() {
        return descripcion;
    }

    public void setDescripcion(String descripcion) {
        this.descripcion = descripcion;
    }

    public String getTipo() {
        return tipo;
    }

    public void setTipo(String tipo) {
        this.tipo = tipo;
    }

    public double getTotalConcepto() {
        return totalConcepto;
    }

    public void setTotalConcepto(double totalConcepto) {
        this.totalConcepto = totalConcepto;
    }
    
    
    
    
}

